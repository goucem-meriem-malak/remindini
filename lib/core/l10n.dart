/// All app text, English / French / Arabic, in one place.
class S {
  const S(this.lang);
  final String lang;

  static S of(BuildContext c) => S(Localizations.localeOf(c).languageCode);

  bool get rtl => lang == 'ar';

  String t(String key, [Map<String, String>? params]) {
    var out = _m[lang]?[key] ?? _m['en']![key] ?? key;
    params?.forEach((k, v) => out = out.replaceAll('{$k}', v));
    return out;
  }

  /// Plural-aware text. Keys are stored as `key.one`, `key.two`, `key.few`, `key.other`.
  String plural(String key, int n, [Map<String, String>? params]) {
    final cat = _category(n);
    final map = _m[lang] ?? _m['en']!;
    final k = map.containsKey('$key.$cat') ? '$key.$cat' : '$key.other';
    return t(k, {'n': '$n', ...?params});
  }

  String _category(int n) {
    switch (lang) {
      case 'ar':
        if (n == 1) return 'one';
        if (n == 2) return 'two';
        final r = n % 100;
        if (r >= 3 && r <= 10) return 'few';
        return 'other';
      case 'fr':
        return (n == 0 || n == 1) ? 'one' : 'other';
      default:
        return n == 1 ? 'one' : 'other';
    }
  }

  /// Used by tests to compare languages.
  static Map<String, Map<String, String>> get all => _m;
}

